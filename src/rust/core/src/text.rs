/// A run of ASCII digits as a number, or None if it's empty or too large.
pub(crate) fn number(digits: &str) -> Option<u64> {
    if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    digits.parse().ok()
}
